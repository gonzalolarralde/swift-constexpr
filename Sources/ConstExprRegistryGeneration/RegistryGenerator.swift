import ConstExprMacroImplementation
import Foundation
import SwiftParser
import SwiftParserDiagnostics
import SwiftSyntax

public enum RegistryGenerationError: Error, CustomStringConvertible {
    case diagnostic(String)
    public var description: String {
        switch self { case .diagnostic(let message): return message }
    }
}

public enum RegistryGenerator {
    public struct Source {
        public let path: String
        public let text: String
        public init(path: String, text: String) { self.path = path; self.text = text }
    }

    public static let generatedHeader = "// Generated by generate-constexpr-registry. Do not edit."

    public static func generate(
        module: String,
        registryName: String,
        sameModule: Bool = false,
        sources: [Source]
    ) throws -> String {
        guard isIdentifier(module), isIdentifier(registryName) else {
            throw RegistryGenerationError.diagnostic("module and registry names must be simple Swift identifiers")
        }
        guard Set(sources.map(\.path)).count == sources.count else {
            throw RegistryGenerationError.diagnostic("the input list contains duplicate source paths")
        }
        let parsed = sources.sorted { $0.path < $1.path }.map { ($0, Parser.parse(source: $0.text)) }
        var issues: [String] = []
        let index = RegistrySourceIndex(module: module)
        for (source, tree) in parsed {
            let converter = SourceLocationConverter(fileName: source.path, tree: tree)
            for diagnostic in ParseDiagnosticsGenerator.diagnostics(for: tree)
                where diagnostic.diagMessage.severity == .error
            {
                let location = converter.location(for: diagnostic.position)
                issues.append("\(source.path):\(location.line):\(location.column): error: \(diagnostic.message)")
            }
            index.walk(tree)
        }
        guard issues.isEmpty else { throw RegistryGenerationError.diagnostic(issues.joined(separator: "\n")) }
        var records: [RegistryDiscoveryRecord] = []
        for (source, tree) in parsed {
            let scanner = RegistrySourceScanner(path: source.path, tree: tree, sameModule: sameModule)
            scanner.walk(tree)
            issues += scanner.issues
            records += scanner.records
        }
        issues += index.issues
        guard issues.isEmpty else { throw RegistryGenerationError.diagnostic(issues.joined(separator: "\n")) }

        // A directly annotated member may already be in its enclosing nominal
        // provider. Compare the adapters actually emitted by the shared macro
        // implementation, never guesses based on the member's name alone.
        let roots = records.filter { if case .root = $0.entry.kind { return true }; return false }
        func normalizedKeys(_ record: RegistryDiscoveryRecord) -> Set<String> {
            Set(record.entry.registrationKeys.map {
                let qualified = index.qualifyExpression($0, owner: record.entry.owner)
                return Parser.parse(source: qualified).tokens(viewMode: .sourceAccurate).map(\.text).joined(separator: " ")
            })
        }
        let rootKeys = roots.map { ($0, normalizedKeys($0)) }
        records = records.filter { record in
            guard case .declaration = record.entry.kind,
                  !record.entry.registrationKeys.isEmpty else { return true }
            return !rootKeys.contains { root, keys in
                root.path == record.path
                    && root.entry.declaration.position < record.entry.declaration.position
                    && root.entry.declaration.endPosition > record.entry.declaration.endPosition
                    && normalizedKeys(record).isSubset(of: keys)
            }
        }

        var extensions: [String: [String]] = [:]
        var rootNames: Set<String> = []
        for record in records {
            switch record.entry.kind {
            case .root(let name):
                let name = index.qualifyType(name, owner: record.entry.owner)
                guard rootNames.insert(name).inserted else {
                    throw RegistryGenerationError.diagnostic("duplicate nominal registry provider for \(name)")
                }
            case .namedExtension(let owner, let name):
                let owner = index.qualifyType(owner, owner: nil)
                guard !(extensions[owner] ?? []).contains(name) else {
                    throw RegistryGenerationError.diagnostic("duplicate named extension provider \(owner).\(name)")
                }
                extensions[owner, default: []].append(name)
            case .declaration: break
            }
        }
        for owner in extensions.keys.sorted() where !rootNames.contains(owner) {
            throw RegistryGenerationError.diagnostic("named extension of \(owner) requires an @ConstExpr root in the selected module")
        }

        var selections: [String] = []
        var namedSelections: [String] = []
        var seen: Set<String> = []
        for record in records {
            let selection: String
            switch record.entry.kind {
            case .root(let type):
                let type = index.qualifyType(type, owner: record.entry.owner)
                if let names = extensions[type] {
                    let names = names.sorted().map { "\"\($0)\"" }.joined(separator: ", ")
                    namedSelections.append("#constExprRegistry(for: \(type).self, extensions: [\(names)])")
                    continue
                }
                selection = type + ".self"
            case .declaration(let source):
                selection = index.qualifyExpression(source, owner: record.entry.owner)
            case .namedExtension: continue
            }
            guard seen.insert(selection).inserted else {
                throw RegistryGenerationError.diagnostic("duplicate registry selector: \(selection)")
            }
            selections.append(selection)
        }
        let imports = (Set(index.imports).subtracting(["import ConstExpr", "import \(module)"]))
            .sorted()
        var lines = [generatedHeader, "// Module: \(module)", "// Registry: \(registryName)", "", "import ConstExpr"]
        if !sameModule { lines.append("import \(module)") }
        lines += imports
        lines += ["", "enum \(registryName) {", "    static let value = #constExprRegistry("]
        for (offset, selection) in selections.enumerated() {
            lines.append("        \(selection)\(offset + 1 == selections.count ? "" : ",")")
        }
        lines.append("    )" + namedSelections.map { ".appending(contentsOf: \($0))" }.joined())
        lines += ["}", ""]
        let output = lines.joined(separator: "\n")
        let diagnostics = ParseDiagnosticsGenerator.diagnostics(for: Parser.parse(source: output))
        guard !diagnostics.contains(where: { $0.diagMessage.severity == .error }) else {
            throw RegistryGenerationError.diagnostic("generated selectors are not valid Swift syntax; use an explicit manual registry for these declarations")
        }
        return output
    }

    public static func isIdentifier(_ name: String) -> Bool {
        guard let first = name.utf8.first,
              first == 95 || (65...90).contains(first) || (97...122).contains(first) else { return false }
        return name.utf8.allSatisfy { $0 == 95 || (65...90).contains($0) || (97...122).contains($0) || (48...57).contains($0) }
    }
}
